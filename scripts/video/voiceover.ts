/**
 * Writes voiceover.md from the rendered timeline, so its timestamps always
 * match out/manifest.json for the cut that was just recorded.
 */
import { WORDS_PER_SECOND, wordCount, type Mode, type Scene } from "./scenes"

export interface TimedScene {
  readonly scene: Scene
  readonly start: number
  readonly end: number
}

const stamp = (seconds: number): string => {
  const whole = Math.round(seconds * 10) / 10
  const minutes = Math.floor(whole / 60)
  const rest = (whole - minutes * 60).toFixed(1).padStart(4, "0")
  return `${minutes}:${rest}`
}

const TITLES: Record<string, string> = {
  intro: "Intro Card",
  problem: "The Problem",
  "ring-live": "Ring Linking, Device Check, And Live View",
  scheduler: "Scheduler: Agency Today",
  compliance: "Compliance And Evidence Pack",
  family: "Family On A Phone",
  caregiver: "Caregiver Note",
  ask: "Ask VisitProof For Alexa+",
  architecture: "How It Is Built",
  outro: "Closing Card",
}

export function voiceoverMarkdown(timeline: readonly TimedScene[], mode: Mode): string {
  const total = timeline.at(-1)?.end ?? 0
  const words = timeline.reduce((sum, item) => sum + wordCount(item.scene.voiceover), 0)
  const sections = timeline.map(({ scene, start, end }) => {
    const count = wordCount(scene.voiceover)
    const budget = Math.floor(scene.duration * WORDS_PER_SECOND)
    return [
      `### ${stamp(start)} to ${stamp(end)} · ${TITLES[scene.id] ?? scene.id} (\`${scene.id}\`)`,
      "",
      `${scene.duration} seconds, ${count} words (budget ${budget}).`,
      "",
      `> ${scene.voiceover}`,
      "",
    ].join("\n")
  })
  return `# VisitProof Demo Voiceover

Generated by \`scripts/video/record.ts\` for the **${mode}** cut. The timestamps
match \`scripts/video/out/manifest.json\` from the same run. Total length
${total.toFixed(1)} seconds, ${words} words, sized at about ${WORDS_PER_SECOND} words per second so
there is room to breathe between lines. Start each line when its scene starts
and let it finish a little before the cut.

${sections.join("\n")}
## How To Record It

1. Find a quiet room with soft furnishings (a closet or a room with curtains
   works well). Turn off fans and notifications.
2. Use QuickTime Player (File, New Audio Recording) or Voice Memos on a Mac or
   iPhone. Set QuickTime's quality to Maximum.
3. Sit about 30 cm (one forearm) from the microphone, slightly off to the side
   so breaths do not pop.
4. Play \`out/visitproof-demo.mp4\` muted on a second screen and read each line
   when its scene starts. Speak slowly and warmly; a pause is better than a rush.
5. Record a few seconds of silence at the start, then the whole script in one
   take. Redo the take rather than editing single words.
6. Export or save the take as \`voiceover.m4a\` next to this file
   (\`scripts/video/voiceover.m4a\`). If you used Voice Memos, share the memo
   to Files and rename it. \`scripts/video/.gitignore\` ignores \`*.m4a\`,
   \`*.wav\` and \`*.aiff\`, so the recording of your voice never lands in a
   commit.

## Mux The Voiceover Onto The Video

Run from the repository root. \`loudnorm\` brings speech to -16 LUFS (the
YouTube and podcast norm); \`apad\` pads the voice with silence so
\`-shortest\` ends exactly when the video ends instead of cutting it short.

\`\`\`sh
ffmpeg -i scripts/video/out/visitproof-demo.mp4 -i scripts/video/voiceover.m4a \\
  -map 0:v:0 -map 1:a:0 -c:v copy \\
  -af "loudnorm=I=-16:TP=-1.5:LRA=11,apad" -c:a aac -b:a 192k -ar 48000 \\
  -shortest -movflags +faststart scripts/video/out/visitproof-demo-final.mp4
\`\`\`

Check the result with
\`ffprobe -v error -show_entries format=duration -of csv=p=0 scripts/video/out/visitproof-demo-final.mp4\`
(it should match the silent cut, ${total.toFixed(1)} seconds).
`
}
